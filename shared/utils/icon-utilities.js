// Simple function to get icon HTML
function getIcon(iconName, className = '') {
  const icon = ICONS[iconName];
  if (!icon) {
    console.warn(`Icon '${iconName}' not found`);
    return '';
  }
  
  // Add class if provided
  if (className) {
    return icon.replace('<svg', `<svg class="${className}"`);
  }
  
  return icon;
}

